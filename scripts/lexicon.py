"""The Lexicon: one 1080 x 1350 card per entry in data/lexicon.toml, plus LEXICON.md.
Needs the `png` extra and cabinet/: uv run --extra png scripts/lexicon.py"""
import asyncio
import base64
import os
import re
import tomllib
from pathlib import Path

from playwright.async_api import async_playwright

from animal_spirits_brand.palette import UI

ROOT = Path(__file__).resolve().parents[1]
ENTRIES = tomllib.loads((ROOT / "src/animal_spirits_brand/data/lexicon.toml").read_text())["entry"]
FONTS = ("https://fonts.googleapis.com/css2?family=Source+Serif+4:ital,opsz,wght@0,8..60,400;0,8..60,600;1,8..60,400"
         "&family=IBM+Plex+Mono:wght@400;500&display=swap")


def slug(term: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", term.lower().replace("â", "a").replace("'", "")).strip("-")


def uri(rel: str) -> str:
    return "data:image/svg+xml;base64," + base64.b64encode((ROOT / rel).read_bytes()).decode()


def card(i: int, e: dict) -> str:
    ink, paper, muted, border = UI["text"][1], UI["bg"][1], UI["text-muted"][1], UI["border"][1]
    obj = (ROOT / f"cabinet/{e['object']}.svg").read_text().replace("currentColor", ink)
    obj = obj.replace('width="512" height="512"', 'style="display:block;width:520px;height:520px"')
    size = 112 if len(e["term"]) < 16 else 88
    return f"""<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="{FONTS}"><style>
*{{margin:0;box-sizing:border-box}} body{{width:1080px;height:1350px;background:{paper};color:{ink};padding:84px 96px;display:flex;flex-direction:column}}
.top{{display:flex;justify-content:space-between;font:500 24px 'IBM Plex Mono';color:{muted};letter-spacing:.04em}}
h1{{font:600 {size}px/1 'Source Serif 4';letter-spacing:-.015em;margin-top:auto}} h1 i{{font-weight:400;font-size:44px;color:{muted}}}
p{{font:400 46px/1.32 'Source Serif 4';margin-top:30px;max-width:860px}}
.src{{margin-top:44px;padding-top:22px;border-top:2px solid {ink};font:400 24px/1.4 'IBM Plex Mono';color:{muted}}}
.ft{{display:flex;gap:16px;align-items:center;margin-top:36px;font:500 22px 'IBM Plex Mono';color:{muted}}}
</style></head><body><div class="top"><span>LEXICON {i:02}</span><span>{e['pos']}</span></div>
<div style="margin:10px auto 0">{obj}</div>
<h1>{e['term']}</h1><p>{e['text']}</p><div class="src">{e['source']}</div>
<div class="ft"><img src="{uri('logo/favicon.svg')}" style="width:30px;height:30px">animal spirits</div></body></html>"""


async def main() -> None:
    out = ROOT / "social/lexicon"
    out.mkdir(parents=True, exist_ok=True)
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path=os.environ.get("CHROMIUM"))
        page = await b.new_page(viewport={"width": 1080, "height": 1350})
        for i, e in enumerate(ENTRIES, 1):
            await page.set_content(card(i, e), wait_until="networkidle")
            await page.evaluate("document.fonts.ready")
            await page.screenshot(path=str(out / f"{i:02}-{slug(e['term'])}.png"))
        await b.close()
    rows = "\n".join(f"| {i:02} | **{e['term']}** *{e['pos']}* | {e['text']} | {e['source']} |" for i, e in enumerate(ENTRIES, 1))
    (ROOT / "LEXICON.md").write_text(
        "# Lexicon\n\nOne term per post, in order. Cards in `social/lexicon/`, generated by `scripts/lexicon.py` from "
        "`src/animal_spirits_brand/data/lexicon.toml`. Every source names the first statement of the idea or the work that "
        "named it; check one before adding an entry.\n\n| # | Term | Definition | Source |\n| --- | --- | --- | --- |\n" + rows + "\n")


if __name__ == "__main__":
    asyncio.run(main())
